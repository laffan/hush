#!/usr/bin/env node
/**
 * Stamp the frontend bundle with when, from what, and by whom it was
 * built. Runs as part of `npm run build` and `npm run dev`, and again
 * from a tiny Vite plugin (see vite.config.js) so the file can never be
 * missing — `src/build-info.generated.js` is git-ignored.
 *
 * Settings → Debug → Build Info reads this next to the native binary's
 * own stamp (baked in by src-tauri/build.rs). Keeping both matters on
 * iPad, where the web bundle and the native binary come from separate
 * steps: a stale bundle paired with a fresh binary is exactly the kind of
 * thing that makes a bug impossible to reproduce.
 *
 * CI is welcome to override the git fields with HUSH_GIT_BRANCH /
 * HUSH_GIT_COMMIT (detached-HEAD checkouts report no branch name).
 */

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "src/build-info.generated.js");

function git(...args) {
  try {
    return execFileSync("git", args, { cwd: ROOT, stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .trim();
  } catch {
    return "";
  }
}

function readVersion() {
  for (const file of ["src-tauri/tauri.conf.json", "package.json"]) {
    try {
      const version = JSON.parse(readFileSync(resolve(ROOT, file), "utf8")).version;
      if (version) return version;
    } catch { /* try the next one */ }
  }
  return "0.0.0";
}

// SOURCE_DATE_EPOCH keeps reproducible builds reproducible; the wall
// clock is only the fallback.
const epoch = Number.parseInt(process.env.SOURCE_DATE_EPOCH || "", 10);
const builtAt = new Date(Number.isFinite(epoch) ? epoch * 1000 : Date.now()).toISOString();

const branch =
  process.env.HUSH_GIT_BRANCH ||
  // A detached HEAD (what CI usually checks out) reports "HEAD"; fall
  // back to whichever ref points at this commit so the field still says
  // something useful.
  (() => {
    const head = git("rev-parse", "--abbrev-ref", "HEAD");
    if (head && head !== "HEAD") return head;
    return git("for-each-ref", "--points-at=HEAD", "--format=%(refname:short)", "refs/heads")
      .split("\n")[0] || "";
  })();

const commit = process.env.HUSH_GIT_COMMIT || git("rev-parse", "--short", "HEAD");
const dirty = !!git("status", "--porcelain");

const info = {
  version: readVersion(),
  builtAt,
  branch: branch || "unknown",
  commit: commit ? `${commit}${dirty ? "-dirty" : ""}` : "unknown",
  commitSubject: git("log", "-1", "--format=%s"),
  commitDate: git("log", "-1", "--format=%cI"),
  // Tauri v2 exports TAURI_ENV_DEBUG to the beforeBuildCommand; outside
  // that (a bare `vite build`) fall back to NODE_ENV.
  mode: process.env.TAURI_ENV_DEBUG === "true" || process.env.NODE_ENV === "development"
    ? "debug"
    : "release",
  node: process.version,
};

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `// Generated by scripts/gen-build-info.mjs — do not edit, do not commit.\n` +
    `export const BUILD_INFO = ${JSON.stringify(info, null, 2)};\n`,
);

if (process.env.HUSH_BUILD_INFO_QUIET !== "1") {
  console.log(`build-info: ${info.version} ${info.branch}@${info.commit} (${info.builtAt})`);
}
